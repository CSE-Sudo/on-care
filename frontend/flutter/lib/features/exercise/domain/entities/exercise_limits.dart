/// 운동 값의 입력 상한 — 회원 앱·트레이너 앱·서버가 **같은 수**를 쓴다. (#1904)
///
/// 세트·횟수·중량은 두 앱이 주고받는 같은 값인데 상한이 곳마다 달랐다. 세트는
/// 회원 앱 40, 서버 100, 트레이너 99 로 셋이 다 달랐고 중량은 회원 앱만
/// 500kg 이었다. 그래서 트레이너가 배정한 값을 회원이 직접 적으려 하면 자기
/// 앱에서 막혔다 — 화면에 보이는 수를 옮겨 적을 수 없었다.
///
/// 값은 **지금 쓰이는 것 중 가장 큰 쪽**으로 맞췄다. 좁히면 예전에 저장되던
/// 기록이 거절돼, 고치려는 문제보다 나쁜 것을 만든다.
///
/// 서버 쪽 같은 값은 `backend/app/schemas/exercise_limits.py` 에 있다.
library;

/// 근력 한 기록의 세트 수 상한.
const int kMaxExerciseSets = 100;

/// 근력 한 세트당 횟수 상한.
const int kMaxExerciseReps = 999;

/// 근력 한 기록의 중량 상한(kg). 레그프레스처럼 세 자리 kg 을 쓰는 종목이 있다.
const double kMaxExerciseWeightKg = 1000;

/// 등척성 홀드 한 세트의 버티는 시간 상한(초). 한 시간이다. (#1969)
///
/// 플랭크·행잉처럼 버티는 운동은 한 세트를 회가 아니라 초로 잰다. 한 세트가
/// 한 시간을 넘으면 그것은 홀드가 아니라 다른 운동이다.
const int kMaxExerciseHoldSeconds = 3600;

/// 운동 한 건의 시간 상한(분). 열 시간이다. (#1903, #2071)
///
/// 기록 한 건이 이보다 길 수는 없다고 본다 — 하루치가 아니라 **한 운동**이
/// 차지한 시간이기 때문이다. 시·분·초 휠이 고를 수 있는 끝도 이 값이다.
const int kMaxExerciseMinutes = 600;
