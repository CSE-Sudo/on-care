/// 사진이 없는 끼니의 썸네일 이모지(#2151).
///
/// 음식 이름으로 먼저 고르고, 맞는 것이 없으면 끼니 이모지다. 직접 추가한 끼니는
/// 사진을 받지 않으므로 무엇을 먹었는지 알아볼 단서가 이것뿐이다 — 끼니 이모지만
/// 두면 점심 기록이 모두 같은 🥗 로 보인다.
///
/// 음식은 적힌 순서대로 본다. 대개 첫 줄이 주식이라 그 끼니를 대표한다.
String mealThumbEmoji(MealType mealType, Iterable<String> foodNames) {
  for (final String name in foodNames) {
    final String? emoji = foodEmoji(name);
    if (emoji != null) return emoji;
  }
  return _mealTypeEmoji[mealType] ?? _mealTypeEmoji[MealType.snack]!;
}

/// 음식 이름 하나의 이모지. 표에 없으면 null.
String? foodEmoji(String name) {
  final String key = name.replaceAll(RegExp(r'\s+'), '');
  if (key.isEmpty) return null;
  for (final (String word, String emoji) in _foodKeywords) {
    if (key.contains(word)) return emoji;
  }
  return null;
}

/// 끼니 이모지. 이모지 칩의 바탕은 사진 틀의 자리 표시 색 하나다(#1700).
