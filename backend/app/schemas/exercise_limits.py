"""운동 값의 입력 상한 — 회원과 트레이너가 **같은 수**를 쓴다. (#1904)

세트·횟수·중량은 두 앱이 주고받는 같은 값인데 상한이 곳마다 달랐다. 세트는
회원 앱 40, 회원 백엔드 100, 트레이너 99 로 셋이 다 달랐고 중량은 회원 앱만
500kg 이었다. 그래서 트레이너가 배정할 수 있는 값을 회원이 직접 적으려 하면
자기 앱에서 막히는 일이 생겼다 — 화면에 보이는 수를 옮겨 적을 수 없었다.

값은 **지금 쓰이는 것 중 가장 큰 쪽**으로 맞췄다. 좁히면 예전에 저장되던
요청이 422 로 떨어져, 고치려는 문제보다 나쁜 것을 만든다.

시간(분)의 상한도 여기 있다. 원래 `exercise_api` 에 있었는데(#1903), 같은 종류의
값을 두 집에 두면 다음 사람이 한쪽만 고친다.
"""
from __future__ import annotations

#: 근력 한 항목의 세트 수 상한.
#:
#: 회원 앱은 40, 트레이너는 99 였다. 둘 중 큰 쪽도 회원 백엔드(100)보다
#: 작았으므로 100 으로 맞춘다.
MAX_EXERCISE_SETS = 100

#: 근력 한 세트당 횟수 상한. 원래 세 곳이 모두 같았다 — 값을 옮겨 적었을 뿐이다.
MAX_EXERCISE_REPS = 999

#: 근력 한 항목의 중량 상한(kg). 회원 앱만 500 이었다.
#:
#: 레그프레스처럼 세 자리 kg 을 쓰는 종목이 있어, 트레이너가 적을 수 있는 무게를
#: 회원도 직접 적을 수 있어야 한다.
MAX_EXERCISE_WEIGHT_KG = 1000

#: 운동 한 건의 시간 상한(분). 열 시간이다.
#:
#: 기록 한 건이 이보다 길 수는 없다고 본다 — 하루치 기록이 아니라 **한 운동**이
#: 차지한 시간이기 때문이다. 상한이 없으면 저장된 값이 그대로 주간 합계·유형별
#: 분해·소모 칼로리·목표 달성률로 번지고, 근력이면 `sets_of()` 가 분에서 세트를
#: 환산하므로 세트 수까지 함께 망가진다. 한 번 들어가면 그 행을 지우기 전까지
#: 회원 앱의 그래프와 트레이너 앱의 고객 현황이 같이 잘못된 수를 말한다. (#1903)
#:
#: 세 입력이 같은 값을 쓴다 — 미리보기로 받은 칼로리를 그대로 저장할 수 있어야
#: 하고(`ExerciseCalorieRequest`), 배정 루틴 완료도 같은 기록으로 남는다
#: (`AssignedRoutineCompleteRequest`). 곳마다 다르면 미리보기는 되는데 저장은
#: 422 로 떨어지는 값이 생긴다.
MAX_EXERCISE_MINUTES = 600

#: 등척성 홀드 한 세트의 버티는 시간 상한(초). 한 시간이다. (#1969)
#:
#: 세트 **하나**가 이보다 길 수는 없다고 본다 — 플랭크·행잉처럼 버티는 운동은
#: 분 단위가 이미 길고, 한 세트가 한 시간을 넘으면 그것은 홀드가 아니라 다른
#: 운동이다. `MAX_EXERCISE_SETS` 와 곱해도 `MAX_EXERCISE_SECONDS` 를 넘을 수
#: 있으나, 두 값은 서로 다른 것을 재므로 여기서 묶지 않는다 — 홀드 초는 한
#: 세트의 길이이고 운동 기록의 초는 그 운동에 실제로 쓴 벽시계 시간이다.
MAX_EXERCISE_HOLD_SECONDS = 3600

#: 운동 한 건의 시간 상한(초). `MAX_EXERCISE_MINUTES` 와 같은 길이다. (#1969)
#:
#: 초와 분은 같은 것을 두 단위로 재는 값이라, 상한이 어긋나면 초로는 되는데
#: 분으로는 422 인 기록이 생긴다. 곱으로 파생시켜 둘이 갈라질 자리를 없앤다.
MAX_EXERCISE_SECONDS = MAX_EXERCISE_MINUTES * 60
