DISCARDED_AUDIENCE_TERMS: tuple[str, ...] = ("고혈압", "당뇨", "만성질환", "위험군")

#: 의학적 조언과 근거 없는 단정을 막는 문구. 문장을 만드는 프롬프트는 모두 싣는다.
