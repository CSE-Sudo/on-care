#: 폐기된 스타트 단계 타깃을 가리키는 말. 어떤 프롬프트의 대상 소개에도 나오면 안 된다.
#:
#: `혈압`·`혈당` 은 넣지 않는다 — 안 재는 지표를 물었을 때의 안내
