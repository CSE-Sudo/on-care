/// 숫자와 단위 사이 — 한국어는 붙이고(`1,480kcal`) 영어는 띄운다(`1,480 kcal`).
/// (#3120)
///
/// 문장 안의 단위는 ARB 문구가 언어마다 정한다. 이 함수는 숫자와 단위를 코드에서
/// 이어 붙이는 칸(카드 머리의 `/ 2,000kcal`, 칩의 `310kcal`)이 같은 규칙을 따르게
/// 한다. [locale] 은 `ko`·`ko_KR`·`en` 처럼 언어 코드로 시작하는 문자열이다.
String unitGap(String locale) => locale.startsWith('ko') ? '' : ' ';
